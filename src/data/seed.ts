function buildPermissions(): Permission[] {
  const actions = [
    ['view', 'View records in this module'],
    ['create', 'Create records in this module'],
    ['edit', 'Edit records in this module'],
    ['archive', 'Archive records in this module'],
    ['delete', 'Delete records in this module'],
    ['manage', 'Full administrative control of this module'],
  ] as const

  const permissions: Permission[] = []
  for (const module of MODULES) {
    for (const [action, description] of actions) {
      const key = `${module}.${action}` as PermissionKey
      permissions.push({
        id: `perm-${module}-${action}`,
        key,
        module,
        action,
        description,
      })
    }
  }
  return permissions
}

function grant(roleId: string, keys: string[]) {
  return keys.map((key) => ({
    roleId,
    permissionId: `perm-${key.replace('.', '-')}`,
  }))
}

